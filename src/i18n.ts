export function t(key: string): string {
  const locale = getLocale()
  const m = messages[locale][key] ?? messages.en[key]
  return m ?? key
}

/**
 * Every translation of `key` across all supported locales.
 * Used to detect stored text (e.g. a seeded workflow step label) that merely
 * repeats a label the UI already renders in the current language — such a
 * duplicate would otherwise show up in the wrong language forever, because it
 * was frozen into the database when the sample data was first created.
 */
export function tAllLocales(key: string): string[] {
  const out: string[] = []
  for (const loc of SUPPORTED) {
    const m = messages[loc][key]
    if (m) out.push(m)
  }
  return out
}

/**
 * Locale-aware instruction appended to AI system hints so the assistant
 * answers in the app's current UI language instead of being hardcoded to Vietnamese.
 */
export function aiAnswerLangHint(
  vi: string = "Trả lời ngắn gọn bằng tiếng Việt.",
  en: string = "Answer concisely in English."
): string {
  return getLocale() === "en" ? en : vi
}
