/**
 * Materialize SAMPLE_DATASETS (src/sampleDatasets.ts) into a one-time SQL seed file for
 * quantis.sample_datasets. `getData()` is a generator function (some datasets use Math.random()),
 * so this captures a single, fixed snapshot of whatever it currently produces — nothing is invented,
 * this just transcribes today's output into static rows so existing users see no visible change.
 *
 * Usage: npx tsx scripts/generate-sample-dataset-seed.ts > backend/schema/003_sample_datasets_seed.sql
 * Does NOT touch any database — output is a SQL file only.
 */
import { SAMPLE_DATASETS } from "../src/sampleDatasets.ts";

function sqlString(s: string): string {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function sqlTextArray(arr: string[]): string {
  if (!arr || arr.length === 0) return "ARRAY[]::text[]";
  return "ARRAY[" + arr.map((v) => sqlString(v)).join(", ") + "]::text[]";
}

function sqlJsonbDollar(value: unknown, tag: string): string {
  const json = JSON.stringify(value);
  return `$${tag}$${json}$${tag}$::jsonb`;
}

function main() {
  const lines: string[] = [];
  lines.push("-- Seed: quantis.sample_datasets");
  lines.push("-- Generated by scripts/generate-sample-dataset-seed.ts — one-time materialization of");
  lines.push("-- src/sampleDatasets.ts's SAMPLE_DATASETS (getData() captured once, frozen as static rows).");
  lines.push(`-- Generated at: ${new Date().toISOString()}`);
  lines.push("-- Safe to re-run: ON CONFLICT (id) DO NOTHING (won't clobber admin edits already in the DB).");
  lines.push("");

  SAMPLE_DATASETS.forEach((def, index) => {
    const full = def.getData();
    const header = full[0] ?? [];
    const dataRows = full.slice(1);
    const tag = `qds${index}`;

    lines.push(
      `INSERT INTO __SCHEMA__.sample_datasets (id, name, domain, description, tags, header, rows_data, display_order)`
    );
    lines.push(
      `VALUES (${sqlString(def.id)}, ${sqlString(def.name)}, ${sqlString(def.domain)}, ${sqlString(def.description)}, ${sqlTextArray(
        def.tags ?? []
      )}, ${sqlTextArray(header)}, ${sqlJsonbDollar(dataRows, tag)}, ${index})`
    );
    lines.push(`ON CONFLICT (id) DO NOTHING;`);
    lines.push("");
  });

  process.stdout.write(lines.join("\n") + "\n");
}

main();
